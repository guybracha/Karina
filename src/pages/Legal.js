// מחליף placeholders מהצורה [KEY] בערכים מהמפה
function fillTerms(template, map) {
  return template.replace(/\[([A-Z_]+)\]/g, (_, key) => {
    const val = map?.[key];
    return (val === 0 || val) ? String(val) : `[${key}]`;
  });
}

